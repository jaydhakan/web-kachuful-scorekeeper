// Contact sheets and an audit summary from `RESPONSIVE=1 npx playwright test e2e/responsive.spec.ts`.
// Usage: node tools/responsive/report.mjs <label>   (reads reports/responsive/raw/<label>/)
/* global document -- read inside page.evaluate */
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { chromium } from '@playwright/test';

const label = process.argv[2] ?? 'current';
const raw = resolve(`reports/responsive/raw/${label}`);
const out = resolve('reports/responsive');
if (!existsSync(raw)) throw new Error(`No audit at ${raw}`);

const GROUPS = {
  'phone-portrait': ['320x568', '360x640', '375x667', '390x844', '430x932'],
  'phone-landscape': ['568x320', '740x360', '844x390', '932x430'],
  tablet: ['768x1024', '820x1180', '1024x768', '1180x820'],
  desktop: ['1280x800', '1440x900', '1920x1080', '2560x1440'],
};
const SHEET_PLAYERS = [3, 7];

const browser = await chromium.launch({ channel: process.env.CI ? undefined : 'chrome' });
const page = await browser.newPage();
for (const [group, vps] of Object.entries(GROUPS)) {
  for (const n of SHEET_PLAYERS) {
    const rows = vps.filter((vp) => existsSync(`${raw}/${vp}/${n}`));
    if (!rows.length) continue;
    const screens = readdirSync(`${raw}/${rows[0]}/${n}`)
      .filter((f) => f.endsWith('.png'))
      .sort();
    const H = group === 'desktop' ? 220 : 300;
    const html = `<body style="margin:0;background:#111;color:#ddd;font:14px system-ui">
      ${rows
        .map(
          (vp) => `<div style="display:flex;gap:8px;padding:8px;align-items:flex-start">
        <div style="width:90px;flex:none;padding-top:4px"><b>${vp}</b><br>${n} players</div>
        ${screens
          .map(
            (s) => `<figure style="margin:0;flex:none">
          <img src="file://${raw}/${vp}/${n}/${s}" style="height:${H}px;display:block;outline:1px solid #333">
          <figcaption style="font-size:11px;padding-top:2px">${s.replace('.png', '')}</figcaption></figure>`,
          )
          .join('')}
      </div>`,
        )
        .join('')}</body>`;
    // Loaded as a file so the file:// screenshots are same-origin.
    writeFileSync(`${raw}/_sheet.html`, html);
    await page.goto(`file://${raw}/_sheet.html`, { waitUntil: 'load' });
    const size = await page.evaluate(() => ({
      width: document.body.scrollWidth,
      height: document.body.scrollHeight,
    }));
    await page.setViewportSize(size);
    await page.screenshot({
      path: `${out}/${label}-${group}-${n}p.jpg`,
      type: 'jpeg',
      quality: 72,
      fullPage: true,
    });
  }
}
await browser.close();

// One table per finding kind: which screen, at which viewport and player count.
const KINDS = [
  'primary',
  'offscreenControls',
  'covered',
  'offscreen',
  'clipped',
  'overlaps',
  'scrolls',
  'smallTargets',
  'pageOverflow',
  'shortened',
];
const found = Object.fromEntries(KINDS.map((k) => [k, new Map()]));
for (const f of readdirSync(raw).filter((f) => f.endsWith('.json'))) {
  const [vp, n] = f.replace('.json', '').split('-');
  for (const r of JSON.parse(readFileSync(`${raw}/${f}`, 'utf8'))) {
    for (const k of KINDS) {
      const v = r[k];
      if (!v || (Array.isArray(v) && !v.length)) continue;
      const key = `${r.screen}|${Array.isArray(v) ? v.slice(0, 4).join('; ') : v}`;
      const m = found[k];
      if (!m.has(key)) m.set(key, []);
      m.get(key).push(`${vp}/${n}p`);
    }
  }
}
let md = `# Responsive audit: ${label}\n\nGenerated by \`tools/responsive/report.mjs\` from the Playwright audit (\`e2e/responsive.spec.ts\`). Contact sheets: \`${label}-*.jpg\`.\n`;
for (const k of KINDS) {
  const m = found[k];
  md += `\n## ${k} (${m.size})\n\n`;
  if (!m.size) {
    md += 'None.\n';
    continue;
  }
  md += '| Screen | Detail | Where |\n| --- | --- | --- |\n';
  for (const [key, where] of [...m].sort()) {
    const [screen, detail] = key.split('|');
    const w =
      where.length > 6 ? `${where.slice(0, 6).join(', ')} … (${where.length})` : where.join(', ');
    md += `| ${screen} | ${detail.replace(/\|/g, '\\|').replace(/\n/g, ' ').slice(0, 160)} | ${w} |\n`;
  }
}
writeFileSync(`${out}/audit-${label}.md`, md);
console.log(`Wrote ${out}/audit-${label}.md and contact sheets`);
